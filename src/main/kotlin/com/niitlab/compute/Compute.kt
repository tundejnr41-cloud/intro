package com.niitlab.compute

fun addition(a: Int, b: Int): Int {
    return a + b
}

fun subtraction(a: Int, b: Int): Int {
    return a - b
}

fun multiplication(a: Int, b: Int): Int {
    return a * b
}

fun division(a: Double, b: Double): Double {
    return a / b
}

fun modularity(a: Double, b: Double): Double {
    return a % b
}